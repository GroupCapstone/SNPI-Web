'use client';

import * as React from 'react';
import {
  AlertCircle,
  Check,
  Copy,
  Eye,
  EyeOff,
  KeyRound,
  RefreshCw,
  ShieldAlert,
} from '@/components/icons';

import { Button } from '@/components/ui/button';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';

import { useResetUserPasswordMutation } from '../hooks/use-users';
import type { User } from '../types';

interface ResetPasswordDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  user: User | null;
}

const generateClientPassword = () => {
  const uppers = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  const lowers = 'abcdefghijkmnopqrstuvwxyz';
  const numbers = '23456789';
  const specials = '!@#$%&*';
  const all = uppers + lowers + numbers + specials;

  // Cryptographically secure randomness: this generates a real password.
  const randomIndex = (max: number) => {
    const buffer = new Uint32Array(1);
    const limit = Math.floor(0x100000000 / max) * max;
    let value = 0;
    do {
      crypto.getRandomValues(buffer);
      value = buffer[0];
    } while (value >= limit);
    return value % max;
  };
  const pick = (str: string) => str[randomIndex(str.length)];
  const chars = [pick(uppers), pick(lowers), pick(numbers), pick(specials)];
  for (let i = 0; i < 8; i++) chars.push(pick(all));
  for (let i = chars.length - 1; i > 0; i--) {
    const j = randomIndex(i + 1);
    [chars[i], chars[j]] = [chars[j], chars[i]];
  }
  return chars.join('');
};

export const ResetPasswordDialog = ({ open, onOpenChange, user }: ResetPasswordDialogProps) => {
  const resetMutation = useResetUserPasswordMutation();

  const [mode, setMode] = React.useState<'auto' | 'custom'>('auto');
  const [customPassword, setCustomPassword] = React.useState('');
  const [autoGeneratedPassword, setAutoGeneratedPassword] = React.useState('');
  const [showPassword, setShowPassword] = React.useState(false);
  const [copied, setCopied] = React.useState(false);
  const [errorMessage, setErrorMessage] = React.useState<string | null>(null);
  const [successResult, setSuccessResult] = React.useState<{
    temporaryPassword: string;
    message: string;
  } | null>(null);

  React.useEffect(() => {
    if (open) {
      setMode('auto');
      setCustomPassword('');
      setAutoGeneratedPassword(generateClientPassword());
      setShowPassword(false);
      setCopied(false);
      setErrorMessage(null);
      setSuccessResult(null);
    }
  }, [open, user]);

  if (!user) return null;

  const handleRegenerate = () => {
    setAutoGeneratedPassword(generateClientPassword());
  };

  const handleCopyCredentials = async () => {
    if (!successResult) return;
    const portalUrl = typeof window !== 'undefined' ? `${window.location.origin}/login` : '';
    const textToCopy = `SNPI School Management System - Account Credentials\nUsername: ${user.username}\nTemporary Password: ${successResult.temporaryPassword}\nLogin Portal: ${portalUrl}\n\n*Note: You will be prompted to set your own private password upon signing in.`;

    try {
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback if clipboard API fails
      setCopied(false);
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);

    const temporaryPassword =
      mode === 'custom' ? customPassword.trim() : autoGeneratedPassword.trim();

    if (mode === 'custom') {
      if (temporaryPassword.length < 8) {
        setErrorMessage('Custom password must be at least 8 characters.');
        return;
      }
      if (!/[A-Z]/.test(temporaryPassword)) {
        setErrorMessage('Custom password must contain at least one uppercase letter (A-Z).');
        return;
      }
      if (!/[a-z]/.test(temporaryPassword)) {
        setErrorMessage('Custom password must contain at least one lowercase letter (a-z).');
        return;
      }
      if (!/[0-9]/.test(temporaryPassword)) {
        setErrorMessage('Custom password must contain at least one number (0-9).');
        return;
      }
      if (!/[^a-zA-Z0-9]/.test(temporaryPassword)) {
        setErrorMessage('Custom password must contain at least one special character (!@#$%&*).');
        return;
      }
    }

    try {
      const response = await resetMutation.mutateAsync({
        id: user._id,
        data: { temporaryPassword },
      });

      setSuccessResult({
        temporaryPassword: response.data.temporaryPassword,
        message: response.data.message || 'Password has been reset successfully.',
      });
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Failed to reset user password';
      setErrorMessage(msg);
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-md" onClose={() => onOpenChange(false)}>
        <DialogHeader>
          <div className="flex items-center gap-2">
            <KeyRound className="size-5.5 shrink-0 text-[#023e8a]" />
            <div>
              <DialogTitle className="text-base font-bold text-slate-900">
                Reset User Password
              </DialogTitle>
              <DialogDescription className="text-xs text-slate-500">
                Issue a temporary password with mandatory change on next login.
              </DialogDescription>
            </div>
          </div>
        </DialogHeader>

        {/* Target User Summary Card */}
        <div className="rounded-lg border border-slate-200 bg-slate-50 p-3 text-xs">
          <div className="flex items-center justify-between">
            <div className="font-semibold text-slate-900">{user.username}</div>
            <div className="flex gap-1">
              {user.roles.map((r) => (
                <span
                  key={r}
                  className="rounded bg-slate-200 px-1.5 py-0.5 text-xs font-semibold text-slate-700 uppercase"
                >
                  {r.replace('_', ' ')}
                </span>
              ))}
            </div>
          </div>
          <div className="mt-1 text-slate-500">{user.email}</div>
        </div>

        {errorMessage && (
          <div className="flex items-start gap-2 rounded-lg border border-red-200 bg-red-50 p-3 text-xs text-red-700">
            <AlertCircle className="mt-0.5 size-4 shrink-0 text-red-600" />
            <span>{errorMessage}</span>
          </div>
        )}

        {successResult ? (
          <div className="space-y-4 py-2">
            <div className="flex items-start gap-2.5 rounded-xl border border-emerald-200 bg-emerald-50 p-3.5 text-xs text-emerald-900">
              <Check className="mt-0.5 size-4 shrink-0 text-emerald-600" />
              <div>
                <span className="font-semibold text-emerald-950">Password Reset Complete</span>
                <p className="text-emerald-800">
                  The user&apos;s previous sessions have been terminated. They will be forced to
                  choose a new private password on their next sign-in.
                </p>
              </div>
            </div>

            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-700">
                Temporary Password Generated:
              </label>
              <div className="flex items-center gap-2">
                <div className="flex flex-1 items-center justify-between rounded-lg border border-slate-300 bg-white px-3 py-2 font-mono text-sm font-bold text-[#023e8a]">
                  <span>{successResult.temporaryPassword}</span>
                </div>
                <Button
                  type="button"
                  variant="outline"
                  onClick={handleCopyCredentials}
                  className="flex h-10 items-center gap-1.5 border-[#00509d] text-xs font-semibold text-[#00509d] hover:bg-blue-50"
                >
                  {copied ? (
                    <>
                      <Check className="size-4 text-emerald-600" />
                      <span>Copied!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="size-4" />
                      <span>Copy Details</span>
                    </>
                  )}
                </Button>
              </div>
              <p className="text-xs text-slate-500">
                Provide these temporary credentials securely to the user.
              </p>
            </div>

            <DialogFooter className="mt-4">
              <Button
                type="button"
                onClick={() => onOpenChange(false)}
                className="w-full bg-[#023e8a] text-xs font-semibold text-white hover:bg-[#00509d]"
              >
                Done
              </Button>
            </DialogFooter>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="space-y-4 py-1">
            {/* Mode selection tabs */}
            <div className="flex rounded-lg bg-slate-100 p-1 text-xs">
              <button
                type="button"
                onClick={() => setMode('auto')}
                className={`flex-1 rounded-md py-1.5 font-medium transition-all ${
                  mode === 'auto'
                    ? 'bg-white text-[#023e8a]'
                    : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                Auto-Generate Strong Password
              </button>
              <button
                type="button"
                onClick={() => setMode('custom')}
                className={`flex-1 rounded-md py-1.5 font-medium transition-all ${
                  mode === 'custom'
                    ? 'bg-white text-[#023e8a]'
                    : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                Specify Custom Password
              </button>
            </div>

            {mode === 'auto' ? (
              <div className="space-y-2">
                <label className="block text-xs font-medium text-slate-700">
                  Preview Generated Password
                </label>
                <div className="flex items-center gap-2">
                  <div className="relative flex-1">
                    <Input
                      type={showPassword ? 'text' : 'password'}
                      value={autoGeneratedPassword}
                      readOnly
                      className="h-9 pr-10 font-mono text-xs font-semibold text-slate-900"
                    />
                    <button
                      type="button"
                      onClick={() => setShowPassword(!showPassword)}
                      className="absolute top-2 right-2.5 text-slate-400 hover:text-slate-600"
                      title={showPassword ? 'Hide password' : 'Show password'}
                    >
                      {showPassword ? <EyeOff className="size-4" /> : <Eye className="size-4" />}
                    </button>
                  </div>
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    onClick={handleRegenerate}
                    title="Generate new password"
                    className="h-9 px-2.5"
                  >
                    <RefreshCw className="size-3.5 text-slate-600" />
                  </Button>
                </div>
              </div>
            ) : (
              <div className="space-y-1.5">
                <label className="block text-xs font-medium text-slate-700">
                  Custom Temporary Password <span className="text-rose-500">*</span>
                </label>
                <div className="relative">
                  <Input
                    type={showPassword ? 'text' : 'password'}
                    value={customPassword}
                    onChange={(e) => setCustomPassword(e.target.value)}
                    placeholder="Min 8 chars, uppercase, lowercase, number, symbol"
                    className="h-9 pr-10 text-xs"
                    required
                  />
                  <button
                    type="button"
                    onClick={() => setShowPassword(!showPassword)}
                    className="absolute top-2 right-2.5 text-slate-400 hover:text-slate-600"
                    title={showPassword ? 'Hide password' : 'Show password'}
                  >
                    {showPassword ? <EyeOff className="size-4" /> : <Eye className="size-4" />}
                  </button>
                </div>
                <p className="text-xs text-slate-500">
                  Must meet security complexity (e.g. Temp@2026!).
                </p>
              </div>
            )}

            {/* Security Notice */}
            <div className="flex items-start gap-2 rounded-lg border border-amber-200 bg-amber-50/75 p-2.5 text-xs text-amber-900">
              <ShieldAlert className="mt-0.5 size-4 shrink-0 text-amber-600" />
              <div>
                <span className="font-semibold">Mandatory First-Login Change:</span> The user&apos;s
                account will be flagged to require an immediate password change upon signing in with
                this temporary password.
              </div>
            </div>

            <DialogFooter className="gap-2 sm:gap-0">
              <Button
                type="button"
                variant="outline"
                onClick={() => onOpenChange(false)}
                disabled={resetMutation.isPending}
                className="h-9 text-xs"
              >
                Cancel
              </Button>
              <Button
                type="submit"
                disabled={resetMutation.isPending}
                className="h-9 bg-[#023e8a] text-xs font-semibold text-white hover:bg-[#00509d]"
              >
                {resetMutation.isPending ? 'Resetting Password...' : 'Confirm Reset Password'}
              </Button>
            </DialogFooter>
          </form>
        )}
      </DialogContent>
    </Dialog>
  );
};
